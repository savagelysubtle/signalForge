async def _enrich_matches_with_recs(
    matches: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """Attach recommendation details to match dicts for response building.

    Args:
        matches: List of raw pending_matches rows.

    Returns:
        Same list with ``rec_ticker``, ``rec_action``, ``rec_confidence``,
        and ``rec_entry_price`` fields added.
    """
    if not matches:
        return matches

    client = await get_db()
    rec_ids = list({m["recommendation_id"] for m in matches})
    rec_resp = (
        await client.table("recommendations")
        .select("id, ticker, action, confidence, entry_price")
        .in_("id", rec_ids)
        .execute()
    )
    rec_map = {r["id"]: r for r in (rec_resp.data or [])}

    for m in matches:
        rec = rec_map.get(m["recommendation_id"], {})
        m["rec_ticker"] = rec.get("ticker", "")
        m["rec_action"] = rec.get("action", "")
        m["rec_confidence"] = rec.get("confidence", 0.0)
        m["rec_entry_price"] = rec.get("entry_price")

    return matches


def _match_to_response(m: dict[str, Any]) -> PendingMatchResponse:
    """Convert a match dict to a PendingMatchResponse model.

    Args:
        m: Match dict (from DB or freshly created).

    Returns:
        Validated PendingMatchResponse.
    """
    return PendingMatchResponse(
        id=m["id"],
        recommendation_id=m["recommendation_id"],
        questrade_order_id=m["questrade_order_id"],
        ticker=m["ticker"],
        side=m["side"],
        avg_price=m["avg_price"],
        total_shares=m["total_shares"],
        total_commission=m.get("total_commission", 0.0),
        currency=m.get("currency", "CAD"),
        executed_at=str(m["executed_at"]),
        match_score=m.get("match_score", 0.0),
        match_reason=m.get("match_reason", ""),
        status=m.get("status", "pending"),
        rec_ticker=m.get("rec_ticker", ""),
        rec_action=m.get("rec_action", ""),
        rec_confidence=m.get("rec_confidence", 0.0),
        rec_entry_price=m.get("rec_entry_price"),
    )
